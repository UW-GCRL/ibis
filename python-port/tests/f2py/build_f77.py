def build():
    """Copy, patch, and compile the Fortran sources."""
    if BUILD_DIR.exists():
        shutil.rmtree(BUILD_DIR)
    BUILD_DIR.mkdir(parents=True)

    # Copy and patch header files
    for h in HEADER_FILES:
        src = FORTRAN_SRC / h
        if src.exists():
            text = src.read_text()
            if h == "compar.h":
                text = patch_compar_h(text)
            (BUILD_DIR / h).write_text(text)
        else:
            print(f"WARNING: {h} not found, creating stub")
            (BUILD_DIR / h).write_text(f"c stub for {h}\n")

    # Copy physics files
    for f in PHYSICS_FILES:
        # Use copyfile (not copy2) — CIFS NAS doesn't permit utime
        shutil.copyfile(FORTRAN_SRC / f, BUILD_DIR / f)

    # Create main.f stub and wrapper
    (BUILD_DIR / "main.f").write_text(create_main_stub())
    (BUILD_DIR / "ibis_wrap.f").write_text(create_wrapper())

    # Step 1: Compile all F77 files to .o
    print(f"Building ibis_f77.so (npoi={NPOI})...")
    obj_files = []
    all_f = PHYSICS_FILES + ["main.f"]
    for f in all_f:
        obj = f.replace(".f", ".o")
        cmd = ["gfortran"] + FFLAGS + [f"-I{BUILD_DIR}", "-c",
               str(BUILD_DIR / f), "-o", str(BUILD_DIR / obj)]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            print(f"  FAILED compiling {f}:\n{r.stderr[:500]}")
            sys.exit(1)
        obj_files.append(str(BUILD_DIR / obj))
        print(f"  [ok] {f}")

    # Step 2: Create and compile stubs for missing subroutines
    stubs_src = """\
      subroutine coldstart
      return
      end
c
      subroutine restart(iyrlast)
      integer iyrlast
      iyrlast = 0
      return
      end
"""
    (BUILD_DIR / "stubs.f").write_text(stubs_src)
    for f in ["ibis_wrap.f", "stubs.f"]:
        obj = f.replace(".f", ".o")
        cmd = ["gfortran"] + FFLAGS + [f"-I{BUILD_DIR}", "-c",
               str(BUILD_DIR / f), "-o", str(BUILD_DIR / obj)]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            print(f"  FAILED compiling {f}:\n{r.stderr[:1000]}")
            sys.exit(1)
        obj_files.append(str(BUILD_DIR / obj))
        print(f"  [ok] {f}")

    # Step 3: Link into a shared library (ctypes-based, no f2py)
    print("  Linking shared library...")
    so_path = OUTPUT_DIR / "ibis_f77.so"
    cmd = ["gfortran", "-shared", "-o", str(so_path)] + obj_files + ["-lgfortran"]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        print(f"  FAILED linking:\n{r.stderr[:1000]}")
        sys.exit(1)

    # Verify
    import ctypes
    try:
        lib = ctypes.CDLL(str(so_path))
        lib.wrap_init_constants_()
        print(f"\nSUCCESS: {so_path.name} (constants initialized)")
    except Exception as e:
        print(f"\nWARNING: .so built but verification failed: {e}")


def clean():
    if BUILD_DIR.exists():
        shutil.rmtree(BUILD_DIR)
        print(f"Removed {BUILD_DIR}")
    for f in OUTPUT_DIR.glob("ibis_f77*"):
        # Preserve hand-written Python wrapper; only remove generated artifacts
        if f.name == "ibis_f77_wrapper.py":
            continue
        f.unlink()
        print(f"Removed {f}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--clean", action="store_true")
    args = parser.parse_args()
    if args.clean:
        clean()
    else:
        build()
