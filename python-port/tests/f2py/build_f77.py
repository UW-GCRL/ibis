def patch_compar_h(text: str) -> str:
    text = text.replace(
        "       parameter (nlon = 720,\n"
        "     >           nlat = 360, \n"
        "     >           npoi = 1718,\n"
        "     >           xres = 0.50,\n"
        "     >           yres = 0.50)",
        "c      parameter (nlon = 720,\n"
        "c     >           nlat = 360, \n"
        "c     >           npoi = 1718,\n"
        "c     >           xres = 0.50,\n"
        "c     >           yres = 0.50)"
    )
    old = "c     >           yres = 0.50)\nc\nc global 0.5 x 0.5  grid"
    new = (
        f"c     >           yres = 0.50)\nc\n"
        f"       parameter (nlon = 10,\n"
        f"     >           nlat = 10, \n"
        f"     >           npoi = {NPOI},\n"
        f"     >           xres = 0.50,\n"
        f"     >           yres = 0.50)\nc\n"
        f"c global 0.5 x 0.5  grid"
    )
    text = text.replace(old, new)
    return text


